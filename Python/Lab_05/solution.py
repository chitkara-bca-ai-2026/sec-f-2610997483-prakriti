import math
a = float(input("Enter first number: "))
b = float(input("Enter second number: "))
r = float(input("Enter radius: "))
power = math.pow(a,b)
square_root = math.sqrt(a)
square_root = round(square_root,2)
ceiling = math.ceil(a/b)
zameen = math.floor(a/b)
absolute =  math.fabs(a-b)
area = (math.pi)*(math.pow(r,2))
area = round(area,2)
per = math.pow(a,2)
base = math.pow(b,2)
hypo = per + base
hypo = math.sqrt(hypo)
hypo =  round(hypo,2)
print(f"{a}^{b}              = {power}")
print(f"sqaure root of {a}   = {square_root}")
print(f"ceil of {a}/{b}      = {ceiling}")
print(f"floor of {a}/{b}     = {zameen}")
print(f"absolute differenece = {absolute}")
print(f"Area of circle       = {area}")
print(f"Hypotenuse           = {hypo}")
